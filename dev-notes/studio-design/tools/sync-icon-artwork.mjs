const artwork = Object.fromEntries(Object.entries(glyphs).map(([name, glyph]) => {
  const source = ICON_ARTWORK[glyph];
  if (!source) throw new Error(`Unknown shared icon: ${glyph}`);
  const svg = source.svg(ICON_REGULAR_STROKE).replace('<svg ', `<svg aria-hidden="true" data-dsh-icon="${glyph}" `);
  if (!svg.includes('viewBox=')) throw new Error(`Missing viewBox: ${glyph}`);
  return [name, svg];
}));

const output = new URL('../icon-artwork.js', import.meta.url);
const header = `/* Generated by tools/sync-icon-artwork.mjs from ui-primitives/src/icons/artwork.ts.\n * Uses existing DSH regular-weight SVG artwork for this standalone design prototype.\n * This file does not mount the production React icon components or introduce a CrewON logo.\n */\n`;
await writeFile(output, `${header}const studioIconArtwork = ${JSON.stringify(artwork, null, 2)};\n`);
